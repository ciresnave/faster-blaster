/**
 * @file judge_op_ids.h
 * @brief Canonical operation ID assignments for the judge metadata table.
 *
 * Op IDs are globally unique integers that index into fb_op_judge_table[]
 * and fb_benchmark_stats_t arrays.  Every operation in the faster-blaster
 * operation superset has exactly one ID here, regardless of which judge
 * archetype (direct, factorization, solve, spectral, dnn, ...) evaluates
 * it.  Archetype-specific source files consume IDs from the ranges assigned
 * below; they do not define their own ID namespaces.
 *
 * An ID being defined here does NOT imply a judge implementation exists yet.
 * Unimplemented slots return FB_JUDGE_NOT_IMPLEMENTED at runtime.
 *
 * Block assignments:
 *     0 –   47 : BLAS Level 1
 *    48 –  129 : BLAS Level 2
 *   130 –  249 : BLAS Level 3 (core + batched GEMM)
 *   250 – 1549 : LAPACK (standard s/d/c/z computational, driver, auxiliary,
 *                         eigenvalue, SVD, and triangular routines)
 *  1550 – 1899 : ScaLAPACK (parallel p* distributed routines)
 *  1900 – 1999 : Extended BLAS (cblas_batch / cblas_strided variants)
 *  2000 – 2049 : MKL extensions (mkl_jit, mkl_*omatcopy, mkl_sparse_*)
 *  2050 – 2149 : Deep Neural Network primitives (fb_dnn_*)
 *  2150 – 2249 : FFT (fb_fft_*)
 *  2250 – 2349 : Sparse linear algebra (fb_sparse_*)
 *  2350 – 2499 : Tensor operations + RNG + NCCL collectives
 *  2500 – 2599 : Statistics + Machine Learning
 *  2600 – 2649 : Parallel Primitives (fb_prim_*)
 *  2650 – 2699 : Chemistry / Physics extensions
 *  2700 – 2749 : Vector math (fb_v*)
 *  2750 – 2799 : Spline interpolation (fb_spline_*)
 *  2800 – 2899 : GEMM / LPGEMM fused extensions
 *  2900 – 2999 : Other fb_* operations
 *
 * FB_JUDGE_MAX_OPERATIONS: 3000
 *
 * Total concrete operation names covered: 2254
 * (see FASTER-BLASTER-OPERATIONS-LIST-APPENDIX.md)
 *
 * @copyright Copyright (c) 2025
 * @license MIT OR Apache-2.0
 */

